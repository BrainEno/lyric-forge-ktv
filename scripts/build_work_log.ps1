<#
.SYNOPSIS
  Generates the active work-log summary from the per-entry files in docs/log/entries.

.DESCRIPTION
  Every completed task writes exactly one entry file under docs/log/entries/.
  This script turns the newest entries into the short summary kept in docs/work_log.md.
  Older entries stay in docs/log/entries/ and are listed in docs/work_log_archive.md.

  Modes:
    -Write  rewrite docs/work_log.md from the entry files.
    -Check  fail (exit 1) when docs/work_log.md is stale or an archived entry is
            not referenced from docs/work_log_archive.md.
    default print the generated summary to stdout without touching any file.
#>
param(
    [switch]$Write,
    [switch]$Check,
    [int]$ActiveCount = 8
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$OutputEncoding = [System.Text.Encoding]::UTF8

$repo = Split-Path -Parent $PSScriptRoot
$entriesDir = Join-Path $repo 'docs\log\entries'
$summaryPath = Join-Path $repo 'docs\work_log.md'
$archivePath = Join-Path $repo 'docs\work_log_archive.md'

if (-not (Test-Path $entriesDir)) {
    throw "Entry directory not found: $entriesDir"
}

$entries = New-Object System.Collections.Generic.List[object]
foreach ($file in (Get-ChildItem $entriesDir -Filter '*.md' | Sort-Object Name)) {
    $text = [System.IO.File]::ReadAllText($file.FullName)
    $lines = $text -split "`r?`n"
    if ($lines[0] -notmatch '^# \[(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2})\] (.+)$') {
        throw "Entry file has no valid H1 header: $($file.Name)"
    }
    $timestamp = "$($Matches[1]) $($Matches[2])"
    $title = $Matches[3]
    $commit = ''
    foreach ($line in $lines) {
        if ($line -match '^- Commit: `(.+)`\s*$') { $commit = $Matches[1] }
    }
    $entries.Add([pscustomobject]@{
        Timestamp = $timestamp
        Title     = $title
        Commit    = $commit
        FileName  = $file.Name
    })
}

$ordered = @($entries | Sort-Object -Property Timestamp -Descending)
$active = @($ordered | Select-Object -First $ActiveCount)
$archived = @($ordered | Select-Object -Skip $ActiveCount)

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine('# Work Log (Active)')
[void]$builder.AppendLine()
[void]$builder.AppendLine('<!-- Generated by scripts/build_work_log.ps1 -Write. Do not edit by hand. -->')
[void]$builder.AppendLine()
foreach ($entry in $active) {
    $commit = if ($entry.Commit) { " ``$($entry.Commit)``" } else { '' }
    [void]$builder.AppendLine("- [$($entry.Timestamp)] $($entry.Title)$commit ([entry](log/entries/$($entry.FileName)))")
}
[void]$builder.AppendLine()
[void]$builder.AppendLine("<!-- $($ordered.Count) entries total: $($active.Count) active, $($archived.Count) archived. -->")
[void]$builder.AppendLine()
[void]$builder.AppendLine('- Full entries: `docs/log/entries/`')
[void]$builder.AppendLine('- Older entries: [archive](work_log_archive.md) | stable decisions: [decisions](decisions.md)')
$generated = $builder.ToString().Replace("`r`n", "`n")

if ($Write) {
    $enc = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($summaryPath, $generated, $enc)
    Write-Output "Wrote docs/work_log.md ($($active.Count) active of $($ordered.Count) entries)."
    exit 0
}

if ($Check) {
    $problems = New-Object System.Collections.Generic.List[string]
    $current = if (Test-Path $summaryPath) { ([System.IO.File]::ReadAllText($summaryPath)).Replace("`r`n", "`n") } else { '' }
    if ($current -ne $generated) {
        $problems.Add('docs/work_log.md is stale; run scripts/build_work_log.ps1 -Write.')
    }
    $archiveText = if (Test-Path $archivePath) { [System.IO.File]::ReadAllText($archivePath) } else { '' }
    foreach ($entry in $archived) {
        if ($archiveText -notlike "*$($entry.FileName)*") {
            $problems.Add("Archived entry is not linked from docs/work_log_archive.md: $($entry.FileName)")
        }
    }
    if ($problems.Count -gt 0) {
        Write-Output "Work log check failed ($($problems.Count) problem(s)):"
        $problems | ForEach-Object { Write-Output "  $_" }
        exit 1
    }
    Write-Output "Work log check passed ($($active.Count) active of $($ordered.Count) entries)."
    exit 0
}

Write-Output $generated
